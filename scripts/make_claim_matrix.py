def _bridges_module():
    spec = importlib.util.spec_from_file_location("make_dictionary_bridges", ROOT / "scripts" / "make_dictionary_bridges.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _cell(text) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def load_registry() -> tuple[dict, str]:
    raw = REGISTRY.read_bytes()
    return yaml.safe_load(raw.decode("utf-8")), hashlib.sha256(raw).hexdigest()


def categorize(reg: dict) -> dict[str, list[dict]]:
    """Cada fila en exactamente una categoría; fallo cerrado si un estatuto no tiene categoría o no está en el vocabulario."""
    vocab = set(reg["status_vocabulary"])
    by_status = {s: key for key, statuses, _, _ in CATEGORIES for s in statuses}
    missing = vocab - set(by_status)
    if missing:
        raise SystemExit(f"FALLO CERRADO: estatutos del vocabulario sin categoría en la matriz: {sorted(missing)}")
    if set(STATUS_EN) != vocab:
        raise SystemExit(f"FALLO CERRADO: vocabulario sin traducción inglesa: {sorted(vocab ^ set(STATUS_EN))}")
    out: dict[str, list[dict]] = {key: [] for key, _, _, _ in CATEGORIES}
    for row in reg["claims"]:
        if row["status"] not in vocab:
            raise SystemExit(f"FALLO CERRADO: {row['claim_id']} tiene un estatuto fuera del vocabulario: {row['status']}")
        out[by_status[row["status"]]].append(row)
    return out


def render(reg: dict, sha: str, lang: str) -> str:
    frame, generated = (FRAME_ES, GENERATED_ES) if lang == "es" else (FRAME_EN, GENERATED_EN)
    cats = categorize(reg)
    bmod = _bridges_module()
    tab = bmod.table(reg)
    lines = [frame["title"], "", generated, "", frame["intro"], "", frame["source"].format(sha=sha, n=len(reg["claims"])), "",
             frame["h_matrix"], "", frame["th_matrix"], "|---|---|---|"]
    for key, _, title_es, title_en in CATEGORIES:
        rows = cats[key]
        ids = ", ".join(f"`{r['claim_id']}`" for r in rows) or "—"
        lines.append(f"| {title_es if lang == 'es' else title_en} | {len(rows)} | {ids} |")
    lines += ["", frame["h_bridges"], "", frame["bridges_intro"].format(gaps=bmod.gap_count(tab)), "", frame["th_bridges"], "|---|---|---|"]
    for kind in bmod.KINDS:
        names = [b["bridge"] for b in tab if b["kind"] == kind]
        label = kind if lang == "es" else BRIDGE_KIND_EN[kind]
        lines.append(f"| {label} | {len(names)} | {_cell('; '.join(names)) or '—'} |")
    lines += ["", frame["h_falsifiers"], "", frame["falsifiers_intro"]]
    for key, _, title_es, title_en in CATEGORIES:
        rows = cats[key]
        if not rows:
            continue
        lines += ["", f"### {title_es if lang == 'es' else title_en}", "", frame["th_falsifiers"], "|---|---|---|---|"]
        for r in rows:
            status = r["status"] if lang == "es" else STATUS_EN[r["status"]]
            lines.append(f"| `{r['claim_id']}` | {status} | {_cell(r['falsifier'])} | {_cell(r['artifact'])} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    reg, sha = load_registry()
    texts = {OUT_ES: render(reg, sha, "es"), OUT_EN: render(reg, sha, "en")}
    if "--check" in sys.argv:
        return 0 if all(p.exists() and p.read_text(encoding="utf-8") == t for p, t in texts.items()) else 1
    for p, t in texts.items():
        p.write_text(t, encoding="utf-8")
    print(f"{len(reg['claims'])} claims → {OUT_ES.name}, {OUT_EN.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
