#!/usr/bin/env python
"""Genera la matriz compacta de claims (supuestos, derivaciones, calibraciones, falsadores, huecos) en español y en
inglés DESDE el registro canónico y la tabla de puentes — revisión del autor del 30-sep.

    docs/matriz_claims.md       (español)
    docs/claim_matrix_en.md     (inglés)

Lo que se muestra es el registro, no una narrativa: cada celda sale de `docs/claims_registry.yaml` (estatuto, falsador,
evidencia, artefacto) o de `scripts/make_dictionary_bridges.py` (estatuto de los puentes, leído a su vez del registro).
La versión inglesa traduce el marco (cabeceras, categorías y vocabulario de estatutos) y CITA en español los textos de
cada fila: el registro es la fuente y no se traduce a mano. Guardas: fallo cerrado si una fila tiene un estatuto fuera
del vocabulario o si una categoría queda sin traducción; `tests/test_claim_matrix.py` regenera ambas vistas y falla si
difieren de lo confirmado, si alguna fila falta o se repite, y si el marco usa lenguaje de sobreafirmación.

Uso: python scripts/make_claim_matrix.py [--check]
"""

from __future__ import annotations

import hashlib
import importlib.util
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "docs" / "claims_registry.yaml"
OUT_ES = ROOT / "docs" / "matriz_claims.md"
OUT_EN = ROOT / "docs" / "claim_matrix_en.md"

